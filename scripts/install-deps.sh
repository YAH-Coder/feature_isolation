#!/usr/bin/env bash
set -euo pipefail

want_docs=1
dry_run=0

for arg in "$@"; do
  case "$arg" in
    --no-docs)
      want_docs=0
      ;;
    --dry-run)
      dry_run=1
      ;;
    -h|--help)
      cat <<'EOF'
Usage: scripts/install-deps.sh [--dry-run] [--no-docs]

Options:
  --dry-run   Print actions without executing them
  --no-docs   Skip Doxygen installation
  -h, --help  Show this help message
EOF
      exit 0
      ;;
    *)
      echo "Unknown argument: $arg" >&2
      exit 2
      ;;
  esac
done

ROOT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_MK="${ROOT_DIR}/config.mk"
SHELL_NIX="${ROOT_DIR}/shell.nix"

log() {
  printf '==> %s\n' "$*"
}

die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

run_cmd() {
  if [[ "$dry_run" -eq 1 ]]; then
    printf '[dry-run] '
    printf '%q ' "$@"
    printf '\n'
  else
    "$@"
  fi
}

run_root_cmd() {
  if [[ "$dry_run" -eq 1 ]]; then
    printf '[dry-run] '
    if [[ "${EUID}" -eq 0 ]]; then
      printf '%q ' "$@"
    else
      printf '%q ' sudo "$@"
    fi
    printf '\n'
    return
  fi

  if [[ "${EUID}" -eq 0 ]]; then
    "$@"
  elif command -v sudo >/dev/null 2>&1; then
    sudo "$@"
  else
    die "This action needs root privileges and sudo is not available: $*"
  fi
}

write_file() {
  local target="$1"
  local content="$2"

  if [[ "$dry_run" -eq 1 ]]; then
    echo "[dry-run] would write ${target}:"
    printf '%s\n' "--------------------"
    printf '%s\n' "$content"
    printf '%s\n' "--------------------"
  else
    printf '%s\n' "$content" > "$target"
  fi
}

write_config_mk() {
  local content="$1"
  write_file "$CONFIG_MK" "$content"
}

detect_brew_gxx() {
  local brew_prefix gcc_prefix candidate
  brew_prefix="$(brew --prefix)"
  gcc_prefix="$(brew --prefix gcc 2>/dev/null || true)"

  # Prefer the versioned Homebrew g++ binary if it exists.
  candidate="$(
    {
      ls -1 "${gcc_prefix}/bin"/g++-[0-9]* 2>/dev/null || true
      ls -1 "${brew_prefix}/bin"/g++-[0-9]* 2>/dev/null || true
    } | sort -V | tail -n1
  )"

  if [[ -n "$candidate" ]]; then
    printf '%s\n' "$candidate"
    return 0
  fi

  return 1
}

install_macos() {
  command -v brew >/dev/null 2>&1 || die "Homebrew is required on macOS."

  local packages=(fmt z3 gcc)
  if [[ "$want_docs" -eq 1 ]]; then
    packages+=(doxygen)
  fi

  log "Installing dependencies via Homebrew"
  run_cmd brew install "${packages[@]}"

  local brew_prefix
  brew_prefix="$(brew --prefix)"

  local compiler_line="# Homebrew GCC was not detected; falling back to Makefile default."
  if candidate="$(detect_brew_gxx 2>/dev/null)"; then
    compiler_line="CXX ?= ${candidate}"
  fi

  write_config_mk "# Auto-generated by scripts/install-deps.sh
# Local overrides for this machine.

${compiler_line}
FMT_PREFIX ?= ${brew_prefix}
Z3_PREFIX ?= ${brew_prefix}
"
}

install_debian_ubuntu() {
  command -v apt-get >/dev/null 2>&1 || die "apt-get not found."

  local packages=(build-essential libfmt-dev libz3-dev)
  if [[ "$want_docs" -eq 1 ]]; then
    packages+=(doxygen)
  fi

  log "Installing dependencies via apt"
  run_root_cmd apt-get update
  run_root_cmd apt-get install -y "${packages[@]}"

  write_config_mk "# Auto-generated by scripts/install-deps.sh
# Debian/Ubuntu use system locations by default.
FMT_PREFIX ?= /usr
Z3_PREFIX ?= /usr
"
}

install_arch() {
  command -v pacman >/dev/null 2>&1 || die "pacman not found."

  local packages=(base-devel fmt z3)
  if [[ "$want_docs" -eq 1 ]]; then
    packages+=(doxygen)
  fi

  log "Installing dependencies via pacman"
  run_root_cmd pacman -Sy --needed "${packages[@]}"

  write_config_mk "# Auto-generated by scripts/install-deps.sh
# Arch uses system locations by default.
FMT_PREFIX ?= /usr
Z3_PREFIX ?= /usr
"
}

install_msys2_ucrt64() {
  command -v pacman >/dev/null 2>&1 || die "pacman not found."
  [[ "${MSYSTEM:-}" == "UCRT64" ]] || die "Run this from the MSYS2 UCRT64 shell."

  local packages=(
    mingw-w64-ucrt-x86_64-gcc
    mingw-w64-ucrt-x86_64-make
    mingw-w64-ucrt-x86_64-fmt
    mingw-w64-ucrt-x86_64-z3
  )

  if [[ "$want_docs" -eq 1 ]]; then
    packages+=(mingw-w64-ucrt-x86_64-doxygen)
  fi

  log "Installing dependencies via MSYS2 pacman (UCRT64)"
  run_cmd pacman -S --needed "${packages[@]}"

  write_config_mk "# Auto-generated by scripts/install-deps.sh
# MSYS2 UCRT64 locations.
CXX ?= /ucrt64/bin/g++
FMT_PREFIX ?= /ucrt64
Z3_PREFIX ?= /ucrt64
"
}

install_nixos() {
  command -v nix-shell >/dev/null 2>&1 || command -v nix >/dev/null 2>&1 || die "Nix is required on NixOS."

  log "NixOS detected"
  log "No global package installation will be done."
  log "Use the provided shell.nix for a reproducible dev shell."

  write_config_mk "# Auto-generated by scripts/install-deps.sh
# On NixOS, use: nix-shell
# The compiler and library flags are provided by the Nix shell environment.
"
}

detect_platform_and_install() {
  local uname_s
  uname_s="$(uname -s)"

  # Windows via MSYS2
  if [[ -n "${MSYSTEM:-}" ]] || [[ "${uname_s}" == MINGW* ]] || [[ "${uname_s}" == MSYS* ]]; then
    install_msys2_ucrt64
    return
  fi

  # macOS
  if [[ "${uname_s}" == "Darwin" ]]; then
    install_macos
    return
  fi

  # Linux
  if [[ -f /etc/os-release ]]; then
    # shellcheck disable=SC1091
    . /etc/os-release

    case "${ID:-}" in
      ubuntu|debian)
        install_debian_ubuntu
        return
        ;;
      nixos)
        install_nixos
        return
        ;;
      arch|manjaro|endeavouros)
        install_arch
        return
        ;;
    esac

    case " ${ID_LIKE:-} " in
      *" debian "*)
        install_debian_ubuntu
        return
        ;;
      *" arch "*)
        install_arch
        return
        ;;
    esac
  fi

  die "Unsupported platform. Supported: macOS (Homebrew), Debian/Ubuntu (apt), Arch (pacman), Windows via MSYS2 UCRT64, NixOS (nix-shell)."
}

detect_platform_and_install

if [[ "$dry_run" -eq 1 ]]; then
  log "Dry run complete."
else
  log "Done."
  log "Generated: ${CONFIG_MK}"
fi
